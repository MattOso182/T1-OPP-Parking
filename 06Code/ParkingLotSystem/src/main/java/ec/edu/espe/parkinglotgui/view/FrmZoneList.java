    public void loadZones() {
        DefaultTableModel model = (DefaultTableModel) tblZones.getModel();
        model.setRowCount(0);

        List<Zone> zones = zoneController.getAllZones();
        for (Zone z : zones) {
            model.addRow(new Object[]{
                z.getId(),
                z.getType(),
                z.getCapacity(),
                z.getOccupied()
            });
        }
    }

