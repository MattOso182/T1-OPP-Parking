    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int row = tblBlocks.getSelectedRow();
        if (row == -1) return;

        int id = (int) tblBlocks.getValueAt(row, 0);
        int zoneId = (int) tblBlocks.getValueAt(row, 1);
        int floors = (int) tblBlocks.getValueAt(row, 2);

        new FrmBlockForm(this, new Block(id, zoneId, floors)).setVisible(true);
    }//GEN-LAST:event_btnEditActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int row = tblBlocks.getSelectedRow();
        if (row == -1) return;

        int id = (int) tblBlocks.getValueAt(row, 0);
        blockController.deleteBlock(id);
        loadBlocks();
    }//GEN-LAST:event_jButton3ActionPerformed

