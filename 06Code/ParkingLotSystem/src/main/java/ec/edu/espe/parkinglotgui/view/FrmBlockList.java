    void loadBlocks() {
        model = (DefaultTableModel) tblBlocks.getModel();
        model.setRowCount(0);

        for (Block b : blockController.getAllBlocks()) {
            model.addRow(new Object[]{
                b.getId(),
                b.getZoneId(),
                b.getFloorCount()
            });
        }
    }

