    private void btnRegisterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegisterActionPerformed
           // TODO add your handling code here:
    String licensePlate = txtPlate.getText().trim(); 
    String vehicleType = (String) cmbType.getSelectedItem(); 
    Date entryTime = new Date(); 
        if (licensePlate.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Debe ingresar la Placa del Vehículo.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    try {
        Vehicle newVehicle = new Vehicle(licensePlate, vehicleType, entryTime);
        
        boolean success = this.parkingData.recordVehicleEntry(newVehicle); 
        
        if (success) {
            JOptionPane.showMessageDialog(this, 
                    String.format("Vehículo %s registrado. Hora de Ingreso: %s", 
                                  licensePlate, entryTime.toString()), 
                    "Registro Exitoso", JOptionPane.INFORMATION_MESSAGE);
            
            txtPlate.setText("");
            cmbType.setSelectedIndex(0); 
            
        } else {
             JOptionPane.showMessageDialog(this, 
                     "Error: La placa " + licensePlate + " ya se encuentra registrada en el parqueo.", 
                     "Error de Registro", JOptionPane.ERROR_MESSAGE);
        }
        
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Ocurrió un error: " + e.getMessage(), "Error Grave", JOptionPane.ERROR_MESSAGE);
    }
    
    }//GEN-LAST:event_btnRegisterActionPerformed

