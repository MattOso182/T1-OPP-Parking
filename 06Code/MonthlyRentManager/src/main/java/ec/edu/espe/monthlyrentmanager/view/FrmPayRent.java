    private void cbxMonthActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cbxMonthActionPerformed
        // TODO add your handling code here:
        if(cbxMonth.getSelectedIndex() !=0 ){
            btnPayRent.setEnabled(true);
        }else{
            btnPayRent.setEnabled(false);
        }
        
         if (cbxMonth.getSelectedItem() != null) {

        int months = Integer.parseInt(
                cbxMonth.getSelectedItem().toString()
        );

        double total = controller.getTotalToPay(
                residentId,
                residentName,
                months
        );

        lblValueRental.setText("$" + total);
    
    }
    }//GEN-LAST:event_cbxMonthActionPerformed

    private void btnPayRentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayRentActionPerformed
        // TODO add your handling code here:
    if (cbxMonth.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Please select the number of months",
                "Error",
                JOptionPane.ERROR_MESSAGE);
        return;
    }

    int months = Integer.parseInt(
            cbxMonth.getSelectedItem().toString()
    );

    double total = controller.getTotalToPay(
            residentId,
            residentName,
            months
    );

    JOptionPane.showMessageDialog(this,
            "Payment successful!\n\n"
            + "Resident ID: " + residentId + "\n"
            + "Months: " + months + "\n"
            + "Total Paid: $" + total,
            "Payment Completed",
            JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_btnPayRentActionPerformed

