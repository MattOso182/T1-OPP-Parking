    private void btnUpdateRentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateRentActionPerformed
        // TODO add your handling code here:
         try {
        double newRent = Double.parseDouble(txtValue.getText());

        if (newRent <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Rent value must be greater than 0",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        RentalManager.getInstance().updateMonthlyRent(newRent);

        JOptionPane.showMessageDialog(this,
                "Rent value updated successfully!\n"
                + "New monthly rent: $" + newRent,
                "Success",
                JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid numeric value",
                "Error",
                JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnUpdateRentActionPerformed

